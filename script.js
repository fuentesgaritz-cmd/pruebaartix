function getNested(obj, path) {
  return path.split(".").reduce((acc, key) => acc?.[key], obj);
}

function currentLanguage() {
  const stored = localStorage.getItem("portfolio-language");
  return translations[stored] ? stored : "es";
}

function updateLeafletButton() {
  const scene = document.getElementById("fold-scene");
  const secondary = document.getElementById("leaflet-secondary-toggle");
  if (!scene || !secondary) return;

  const lang = currentLanguage();
  const isOpen = scene.classList.contains("is-open");
  const label = isOpen
    ? translations[lang].feria.dipticoButtonClose
    : translations[lang].feria.dipticoButtonOpen;

  const span = secondary.querySelector("span");
  if (span) span.textContent = label;
}

function setLanguage(lang) {
  if (!translations[lang]) return;

  document.documentElement.lang = lang === "eu" ? "eu" : lang;
  localStorage.setItem("portfolio-language", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = getNested(translations[lang], el.dataset.i18n);
    if (value) el.textContent = value;
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = getNested(translations[lang], el.dataset.i18nAria);
    if (value) el.setAttribute("aria-label", value);
  });

  updateLeafletButton();
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

setLanguage(currentLanguage());

