/* AI variations carousel */
document.querySelectorAll("[data-carousel]").forEach((carousel) => {
  const slides = [...carousel.querySelectorAll(".ai-slide")];
  const dots = [...carousel.querySelectorAll("[data-carousel-dot]")];
  const prevButtons = [...carousel.querySelectorAll("[data-carousel-prev]")];
  const nextButtons = [...carousel.querySelectorAll("[data-carousel-next]")];
  const playButtons = [...carousel.querySelectorAll("[data-carousel-play]")];
  const stopButtons = [...carousel.querySelectorAll("[data-carousel-stop]")];
  const current = carousel.querySelector("[data-carousel-current]");

  if (!slides.length) return;

  let index = Math.max(0, slides.findIndex((slide) => slide.classList.contains("is-active")));
  let isAnimating = false;
  let isPlaying = false;
  let autoplayId = null;

  const AUTOPLAY_DELAY = 5000;
  const MORPH_DURATION = 760;

  function updateUi() {
    dots.forEach((dot, i) => {
      dot.classList.toggle("is-active", i === index);
      dot.setAttribute("aria-pressed", i === index ? "true" : "false");
    });

    if (current) {
      current.textContent = String(index + 1).padStart(2, "0");
    }

    playButtons.forEach((button) => {
      button.classList.toggle("is-active", isPlaying);
      button.setAttribute("aria-pressed", isPlaying ? "true" : "false");
    });

    stopButtons.forEach((button) => {
      button.classList.toggle("is-active", !isPlaying);
      button.setAttribute("aria-pressed", !isPlaying ? "true" : "false");
    });
  }

  function scheduleAutoplay() {
    if (!isPlaying) return;
    window.clearInterval(autoplayId);
    autoplayId = window.setInterval(() => {
      transitionTo(index + 1);
    }, AUTOPLAY_DELAY);
  }

  function startAutoplay() {
    window.clearInterval(autoplayId);
    autoplayId = null;
    isPlaying = true;
    scheduleAutoplay();
    updateUi();
  }

  function stopAutoplay() {
    isPlaying = false;
    window.clearInterval(autoplayId);
    autoplayId = null;
    updateUi();
  }

  function transitionTo(newIndex) {
    if (isAnimating || !slides.length) return;

    const normalizedIndex = (newIndex + slides.length) % slides.length;
    if (normalizedIndex === index) {
      if (isPlaying) scheduleAutoplay();
      return;
    }

    isAnimating = true;

    const oldIndex = index;
    const oldSlide = slides[oldIndex];
    const newSlide = slides[normalizedIndex];

    index = normalizedIndex;

    slides.forEach((slide, i) => {
      if (i !== oldIndex && i !== normalizedIndex) {
        slide.classList.remove("is-active", "is-leaving");
      }
    });

    oldSlide.classList.add("is-leaving");
    newSlide.classList.add("is-active");
    updateUi();

    window.setTimeout(() => {
      oldSlide.classList.remove("is-active", "is-leaving");
      isAnimating = false;
    }, MORPH_DURATION);

    if (isPlaying) scheduleAutoplay();
  }

  prevButtons.forEach((button) => {
    button.addEventListener("click", () => transitionTo(index - 1));
  });

  nextButtons.forEach((button) => {
    button.addEventListener("click", () => transitionTo(index + 1));
  });

  dots.forEach((dot, i) => {
    dot.addEventListener("click", () => transitionTo(i));
  });

  playButtons.forEach((button) => {
    button.addEventListener("click", startAutoplay);
  });

  stopButtons.forEach((button) => {
    button.addEventListener("click", stopAutoplay);
  });

  let touchStartX = null;

  carousel.addEventListener("touchstart", (event) => {
    touchStartX = event.changedTouches[0].clientX;
  }, { passive: true });

  carousel.addEventListener("touchend", (event) => {
    if (touchStartX === null) return;
    const diff = event.changedTouches[0].clientX - touchStartX;

    if (Math.abs(diff) > 45) {
      transitionTo(diff < 0 ? index + 1 : index - 1);
    }

    touchStartX = null;
  }, { passive: true });

  carousel.addEventListener("mouseenter", () => {
    if (isPlaying && autoplayId) {
      window.clearInterval(autoplayId);
      autoplayId = null;
    }
  });

  carousel.addEventListener("mouseleave", () => {
    if (isPlaying && !autoplayId) {
      scheduleAutoplay();
    }
  });

  document.addEventListener("visibilitychange", () => {
    if (document.hidden) {
      if (autoplayId) {
        window.clearInterval(autoplayId);
        autoplayId = null;
      }
    } else if (isPlaying && !autoplayId) {
      scheduleAutoplay();
    }
  });

  slides.forEach((slide, i) => {
    slide.classList.toggle("is-active", i === index);
    slide.classList.remove("is-leaving");
  });

  updateUi();
});




/* Floating stickers background · Noche de los Cuentos */
(() => {
  const orbit = document.querySelector("[data-sticker-orbit]");
  if (!orbit || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  const colorPool = [
    "assets/sticker-snow-color.png",
    "assets/sticker-peter-color.png",
    "assets/sticker-rapunzel-color.png"
  ];

  const monoPool = [
    "assets/sticker-snow-mono.png",
    "assets/sticker-peter-mono.png",
    "assets/sticker-rapunzel-mono.png"
  ];

  const TOTAL_COLOR = 3;
  const TOTAL_MONO = 2;
  const SWAP_EVERY = 10000;
  const FADE_TIME = 900;

  let sprites = [];
  let viewportWidth = 0;
  let pageHeight = 0;
  let lastFrame = performance.now();

  function shuffle(list) {
    const array = [...list];
    for (let i = array.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [array[i], array[j]] = [array[j], array[i]];
    }
    return array;
  }

  function updateBounds() {
    viewportWidth = Math.max(
      document.documentElement.clientWidth,
      window.innerWidth || 0
    );
    pageHeight = Math.max(
      document.body.scrollHeight,
      document.documentElement.scrollHeight,
      window.innerHeight || 0
    );
  }

  function randomBetween(min, max) {
    return min + Math.random() * (max - min);
  }

  function randomDirection() {
    const angle = randomBetween(0, Math.PI * 2);
    const speed = randomBetween(7, 16); // px/s, suave y constante
    return {
      vx: Math.cos(angle) * speed,
      vy: Math.sin(angle) * speed
    };
  }

  function buildSticker(src, type) {
    const el = document.createElement("div");
    el.className = `sticker-float sticker-float--${type}`;
    el.setAttribute("aria-hidden", "true");

    const img = document.createElement("img");
    img.src = src;
    img.alt = "";
    img.draggable = false;

    el.appendChild(img);
    orbit.appendChild(el);

    const isRapunzel = src.includes("rapunzel");
    const size = isRapunzel
      ? randomBetween(120, 220)
      : randomBetween(90, 170);

    const scale = randomBetween(.88, 1.12);
    const rotation = randomBetween(-10, 10);
    const spin = randomBetween(-3, 3);
    const dir = randomDirection();

    const sprite = {
      el,
      src,
      type,
      width: size,
      height: isRapunzel ? size * 2.9 : size,
      x: randomBetween(0, Math.max(24, viewportWidth - size)),
      y: randomBetween(0, Math.max(24, pageHeight - (isRapunzel ? size * 2.9 : size))),
      vx: dir.vx,
      vy: dir.vy,
      scale,
      rotation,
      spin
    };

    el.style.width = `${sprite.width}px`;
    el.style.opacity = type === "color" ? String(randomBetween(.15, .23)) : String(randomBetween(.08, .14));

    return sprite;
  }

  function chooseSet() {
    const monoSelection = shuffle(monoPool).slice(0, TOTAL_MONO);
    const colorSelection = shuffle(colorPool).slice(0, TOTAL_COLOR);

    return [
      ...colorSelection.map((src) => ({ src, type: "color" })),
      ...monoSelection.map((src) => ({ src, type: "mono" }))
    ];
  }

  function clearSprites() {
    sprites.forEach((sprite) => sprite.el.remove());
    sprites = [];
  }

  function populate() {
    updateBounds();
    clearSprites();
    const selected = chooseSet();
    sprites = selected.map(({ src, type }) => buildSticker(src, type));
  }

  function softRefresh() {
    const oldSprites = [...sprites];
    oldSprites.forEach((sprite) => {
      sprite.el.classList.add("is-fading");
    });

    window.setTimeout(() => {
      populate();
    }, FADE_TIME * 0.6);

    window.setTimeout(() => {
      oldSprites.forEach((sprite) => sprite.el.remove());
    }, FADE_TIME + 80);
  }

  function tick(now) {
    const dt = Math.min(0.05, (now - lastFrame) / 1000);
    lastFrame = now;

    for (const sprite of sprites) {
      sprite.x += sprite.vx * dt;
      sprite.y += sprite.vy * dt;
      sprite.rotation += sprite.spin * dt;

      if (sprite.x > viewportWidth + sprite.width) sprite.x = -sprite.width;
      if (sprite.x < -sprite.width) sprite.x = viewportWidth + sprite.width;

      if (sprite.y > pageHeight + sprite.height) sprite.y = -sprite.height;
      if (sprite.y < -sprite.height) sprite.y = pageHeight + sprite.height;

      sprite.el.style.transform = `translate3d(${sprite.x}px, ${sprite.y}px, 0) rotate(${sprite.rotation}deg) scale(${sprite.scale})`;
    }

    window.requestAnimationFrame(tick);
  }

  let refreshTimer = null;

  function start() {
    populate();
    lastFrame = performance.now();

    if (refreshTimer) window.clearInterval(refreshTimer);
    refreshTimer = window.setInterval(() => {
      softRefresh();
    }, SWAP_EVERY);

    window.requestAnimationFrame(tick);
  }

  let resizeTimer = null;
  window.addEventListener("resize", () => {
    updateBounds();
    window.clearTimeout(resizeTimer);
    resizeTimer = window.setTimeout(() => {
      softRefresh();
    }, 220);
  });

  window.addEventListener("load", updateBounds);
  start();
})();
